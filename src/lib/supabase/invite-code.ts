/**
 * আমন্ত্রণ কোড তৈরি।
 *
 * কেন এটি নিরাপত্তার দিক থেকে গুরুত্বপূর্ণ
 * ---------------------------------------
 * F5 বন্ধ করার সময় ধরে নেওয়া হয়েছিল যে সম্পূর্ণ কোড অনুমান করা যায় না।
 * invites টেবিল আর বাইরের কারো পড়ার মতো নয়, তাই ভেতরে ঢোকার একমাত্র পথ
 * পুরো কোডটি জানা, আর সেই খোঁজ নেওয়ার একমাত্র উপায় invite_preview()।
 * R10 সেটিকে প্রতি পরিচয়ে ১৫ মিনিটে পাঁচ ভুল চেষ্টায় বেঁধে দিয়েছে।
 *
 * দুটি সুরক্ষাই সম্পূর্ণভাবে দাঁড়িয়ে আছে কোডটি লম্বা ও এলোমেলো হওয়ার উপর।
 * ছোট বা অনুমানযোগ্য কোড হলে throttle দেয়াল নয়, গতিরোধক মাত্র।
 * `supabase/01-schema.sql` নিজেই সে কথা লিখে রেখেছে:
 *   "কোড অবশ্যই যথেষ্ট এলোমেলো হতে হবে; ছোট বা অনুমানযোগ্য কোড এই সুরক্ষা নষ্ট করে।"
 *
 * তাই: crypto.getRandomValues — Math.random নয়, timestamp নয়, counter নয়,
 * আর দোকানের নাম বা id-র কোনো অংশ নয়। কোডে দোকানের কোনো চিহ্ন থাকলে সেটি
 * নিজেই একটি তথ্য ফাঁস, আর অনুমানের পরিসরও ছোট করে দেয়।
 *
 * বর্ণমালা — ফোনে পড়ে শোনানোর উপযোগী (Crockford Base32)
 * ------------------------------------------------------
 * বাদ দেওয়া হয়েছে চারটি অক্ষর, কারণ সেগুলো অন্য চিহ্নের সঙ্গে গুলিয়ে যায়:
 *   I  — '1'-এর মতো দেখায়
 *   L  — '1'-এর মতো দেখায়
 *   O  — '0'-এর মতো দেখায়
 *   U  — 'V'-এর সঙ্গে গুলিয়ে যায়, আর অনিচ্ছাকৃত শব্দ তৈরি হওয়াও আটকায়
 * ফলে থাকে ১০টি সংখ্যা + ২২টি অক্ষর = ৩২টি চিহ্ন।
 *
 * ৩২ ঠিক 2^5, তাই প্রতি চিহ্নে ৫ বিট এবং ৫ বিটের মুখোশ (mask) দিয়ে সরাসরি
 * বাছাই করা যায় — কোনো পক্ষপাত (modulo bias) থাকে না। এটিই ৩২ ধরে রাখার
 * কারণ: 2/Z, 5/S, 8/B, 6/G-ও হাতের লেখায় গুলিয়ে যেতে পারে, কিন্তু সেগুলো
 * বাদ দিলে বর্ণমালা ২-এর ঘাত থাকে না, আর নিরপেক্ষ বাছাই জটিল হয়ে যায়।
 * তার বদলে পর্দায় কোডটি চার-চার করে ভাগ করে দেখানো হয় (দেখুন formatForDisplay),
 * যাতে পড়ে শোনানো সহজ হয়।
 *
 * দৈর্ঘ্যের হিসাব
 * ---------------
 *   প্রতি চিহ্নে বিট      = log2(32) = 5
 *   দরকার                 ≥ 2^64, অর্থাৎ ≥ ৬৪ বিট
 *   সর্বনিম্ন দৈর্ঘ্য      = ceil(64 / 5) = 12.8 → ১৩ চিহ্ন (৬৫ বিট)
 *   বেছে নেওয়া হয়েছে      = ১৬ চিহ্ন → 16 × 5 = **৮০ বিট** (≈ 1.2 × 10^24)
 *
 * ১৬ নেওয়া হয়েছে ৬৫-এর বদলে হাতে কিছু জায়গা রাখতে, আর চার-চার করে ভাগ
 * করা যায় বলে। সুন্দর দেখানোর জন্য এটি কমানো যাবে না — ১৩-ই একেবারে তলা।
 */

/** ১০ সংখ্যা + ২২ অক্ষর = ৩২। I, L, O, U বাদ (উপরের নোট দেখুন)। */
export const INVITE_ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';

/** কোডের দৈর্ঘ্য। ১৬ × ৫ বিট = ৮০ বিট। তলা ১৩; এর নিচে নামানো নিষেধ। */
export const INVITE_CODE_LENGTH = 16;

/** প্রতি চিহ্নে বিট — ৩২ = 2^5। */
export const INVITE_BITS_PER_CHAR = 5;

/** কোডে কত বিট এলোমেলোতা আছে। */
export const INVITE_ENTROPY_BITS = INVITE_CODE_LENGTH * INVITE_BITS_PER_CHAR;

/** ৫ বিটের মুখোশ — ৩২টি চিহ্নের ঠিক একটিতে ফেলে, পক্ষপাত ছাড়া। */
const FIVE_BIT_MASK = 0b11111;

/**
 * একটি নতুন আমন্ত্রণ কোড।
 *
 * crypto.getRandomValues না থাকলে ফাঁকা বা দুর্বল কোড ফেরানো হয় না — থেমে যায়।
 * দুর্বল কোড মানে F5 আর R10 দুটোই অর্থহীন, তাই নিঃশব্দে নেমে যাওয়ার চেয়ে
 * জোরে থামাই ঠিক।
 */
export function generateInviteCode(length: number = INVITE_CODE_LENGTH): string {
  if (length < 13) {
    throw new Error('আমন্ত্রণ কোড ১৩ চিহ্নের চেয়ে ছোট হতে পারবে না (৬৪ বিটের তলা)');
  }

  const c: Crypto | undefined =
    typeof globalThis !== 'undefined' ? (globalThis.crypto as Crypto | undefined) : undefined;
  if (!c || typeof c.getRandomValues !== 'function') {
    throw new Error(
      'নিরাপদ এলোমেলো সংখ্যা পাওয়া যায়নি (crypto.getRandomValues নেই) — আমন্ত্রণ কোড তৈরি করা হলো না',
    );
  }

  const bytes = new Uint8Array(length);
  c.getRandomValues(bytes);

  let out = '';
  for (let i = 0; i < length; i++) {
    // ৫ বিট নিয়ে সরাসরি সূচক — ৩২ চিহ্ন হওয়ায় ভাগশেষের পক্ষপাত নেই।
    out += INVITE_ALPHABET[bytes[i] & FIVE_BIT_MASK];
  }
  return out;
}

/**
 * পর্দায় দেখানোর জন্য চার-চার করে ভাগ — শুধু **দেখানোর** জন্য।
 * আসল মানে কোনো হাইফেন নেই, কারণ invite_preview() হুবহু মিল খোঁজে
 * (`code = p_code`)। তাই কপি বাটন সর্বদা আসল মানটিই কপি করে।
 */
export function formatForDisplay(code: string, groupSize = 4): string[] {
  const groups: string[] = [];
  for (let i = 0; i < code.length; i += groupSize) {
    groups.push(code.slice(i, i + groupSize));
  }
  return groups;
}
